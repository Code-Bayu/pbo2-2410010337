    private void tampilkanRingkasan() {
        String kelas;
        if (ekonomiRadio.isSelected()) {
        kelas = "Ekonomi";
        } else if (bisnisRadio.isSelected()) {
        kelas = "Bisnis";
        } else {
        kelas = "Eksekutif";
        }
            List<String> fasilitasTambahan = new ArrayList<>();
                for (JCheckBox cb : List.of(bagasiCheck, makanCheck, asuransiCheck)) {
                    if (cb.isSelected()) {
                    fasilitasTambahan.add(cb.getText());
                }
            }
        String pesan = "Nama Pemesan: " + namaField.getText()
            + "\nNomor: " + nomorField.getText()
            + "\nKota Tujuan: " + kotaCombo.getSelectedItem()
            + "\nKelas: " + kelas
            + "\nFasilitas Tambahan: " + (fasilitasTambahan.isEmpty() ? "-" : String.join(", ", fasilitasTambahan))
            + "\nCatatan: " + (catatanArea.getText().isBlank() ? "-" : catatanArea.getText());
        JOptionPane.showMessageDialog(this, pesan, "Data Pemesan",
        JOptionPane.INFORMATION_MESSAGE);
    }
    private void gantiTema(boolean gelap) {
        if (gelap) {
            FlatDarkLaf.setup();
    } else {
            FlatLightLaf.setup();
    }
    FlatLaf.updateUI(); // terapkan tema baru ke semua jendela yang terbuka
    temaToggle.setText(gelap ? "Mode Terang" : "Mode Gelap");
    }
    


